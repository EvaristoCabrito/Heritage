// Verificação local da ordenação e da seleção de backend sem navegador.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const window = {};
const context = { window, navigator: {}, document: { createElement: () => ({ getContext: () => null }) }, Float32Array };
vm.runInNewContext(fs.readFileSync('gpu-2d.js', 'utf8'), context);
const { batchesFor, create, SpatialIndex, ParticlePool, Camera2D, Scene2D, TextureStore, Animation2D, profiles } = window.HeritageGPU2D;
const a = {}, b = {};
const sprite = (texture, x) => ({ texture, x, y: 2, width: 3, height: 4 });
const result = batchesFor([sprite(a, 1), sprite(a, 2), sprite(b, 3), sprite(a, 4)]);
assert.equal(result.data.length, 48);
assert.deepEqual(Array.from(result.data.slice(0, 12)), [1, 2, 3, 4, 0, 0, 1, 1, 1, 1, 1, 1]);
assert.deepEqual(Array.from(result.batches, batch => [batch.start, batch.count]), [[0, 2], [2, 1], [3, 1]]);
assert.equal(result.batches[0].texture, a);
assert.equal(result.batches[2].texture, a);
assert.equal(batchesFor([]).data.length, 0);
const index = new SpatialIndex(10);
index.set('first', { x: -5, y: -5, width: 20, height: 20 }, 'first');
index.set('second', { x: 10, y: 0, width: 5, height: 5 }, 'second');
assert.deepEqual(Array.from(index.query({ x: 0, y: 0, width: 20, height: 10 })), ['first', 'second']);
index.set('first', { x: 100, y: 100, width: 5, height: 5 }, 'first');
assert.deepEqual(Array.from(index.query({ x: 0, y: 0, width: 20, height: 10 })), ['second']);
assert.equal(index.delete('second'), true);
assert.equal(index.query({ x: 0, y: 0, width: 20, height: 10 }).length, 0);
const particles = new ParticlePool(1);
const particle = particles.emit({ life: 2, vx: 3 });
assert.equal(particles.emit({ life: 1 }), null);
particles.update(1);
assert.equal(particle.x, 3);
particles.update(1);
assert.equal(particles.active, 0);
assert.equal(particles.emit({ life: 1 }), particle);
const camera = new Camera2D(-20, -10, 2);
const position = camera.toWorld(...Object.values(camera.toScreen(12, 15)));
assert.equal(position.x, 12); assert.equal(position.y, 15);
const scene = new Scene2D(10);
scene.set('front', { x: 15, y: 10, width: 2, height: 2, layer: 2 });
scene.set('back', { x: 12, y: 10, width: 2, height: 2, layer: 1 });
scene.set('outside', { x: 100, y: 100, width: 2, height: 2 });
const visible = scene.visible(camera, 20, 20);
assert.deepEqual(Array.from(visible, item => item.id), ['back', 'front']);
assert.equal(visible[0].x, 4);
const destroyed = [];
const store = new TextureStore({ texture: source => ({ destroy: () => destroyed.push(source.id) }) }, 32);
const image = id => ({ id, width: 2, height: 2 });
const held = store.acquire('a', image('a'));
assert.equal(store.acquire('a', image('unused')), held);
store.acquire('b', image('b'));
assert.throws(() => store.acquire('c', image('c')), /Orçamento/);
store.release('a'); store.release('a');
store.acquire('c', image('c'));
assert.deepEqual(destroyed, ['a']);
store.destroy(); assert.equal(store.bytes, 0);
const animation = new Animation2D(['a', 'b', 'c'], 0.5);
assert.equal(animation.frame, 'a');
assert.equal(animation.advance(0.6), 'b');
assert.equal(animation.advance(1), 'a');
animation.reset(); assert.equal(animation.frame, 'a');
const once = new Animation2D(['a', 'b'], 1, false);
assert.equal(once.advance(20), 'b');
assert(profiles.Ultra.textureBudget > profiles.Performance.textureBudget);
create().then(() => { throw new Error('A ausência dos dois backends deveria falhar'); }, error => {
  assert.match(error.message, /WebGPU indisponível.*WebGL 2/);
  console.log('Sprites 2D: ordem, instâncias, índice espacial, partículas e erro de backends verificados.');
}).catch(error => { console.error(error); process.exitCode = 1; });
